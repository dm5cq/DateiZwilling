class Tr:
    def __init__(self, lang: str = "de"):
        self.lang = lang if lang in ("de", "en") else "de"

    def __call__(self, key: str, **kw) -> str:
        entry = TEXTS.get(key)
        if not entry:
            return key
        s = entry.get(self.lang) or entry.get("de") or key
        try:
            return s.format(**kw) if kw else s
        except (KeyError, IndexError, ValueError):
            return s

    def error(self, code: str) -> str:
        key, _, arg = code.partition(":")
        return self(key, x=arg)
